// --- Helper functions ---

export function getContratoById(id: string): ContratoConVotos | undefined {
  return mockContratos.find((c) => c.id === id);
}

export function getContratosStats() {
  const totalContratos = mockContratos.length;
  const valorTotal = mockContratos.reduce((s, c) => s + c.valor_contrato, 0);
  const promedioValor = Math.round(valorTotal / totalContratos);
  const activos = mockContratos.filter((c) => c.estado === "activo").length;

  // By estado
  const porEstado: Record<string, number> = {};
  for (const c of mockContratos) {
    porEstado[c.estado] = (porEstado[c.estado] || 0) + 1;
  }

  // By departamento
  const deptMap = new Map<string, { count: number; valor: number }>();
  for (const c of mockContratos) {
    const d = deptMap.get(c.departamento) || { count: 0, valor: 0 };
    d.count++;
    d.valor += c.valor_contrato;
    deptMap.set(c.departamento, d);
  }
  const porDepartamento = [...deptMap.entries()]
    .map(([nombre, d]) => ({ nombre, count: d.count, valor: d.valor }))
    .sort((a, b) => b.count - a.count);

  // By month
  const mesMap = new Map<string, { count: number; valor: number }>();
  for (const c of mockContratos) {
    const fecha = c.fecha_firma.substring(0, 7); // YYYY-MM
    const d = mesMap.get(fecha) || { count: 0, valor: 0 };
    d.count++;
    d.valor += c.valor_contrato;
    mesMap.set(fecha, d);
  }
  const porMes = [...mesMap.entries()]
    .map(([fecha, d]) => ({ fecha, count: d.count, valor: d.valor }))
    .sort((a, b) => a.fecha.localeCompare(b.fecha));

  // Top entidades
  const entMap = new Map<string, { count: number; valor: number }>();
  for (const c of mockContratos) {
    const d = entMap.get(c.entidad_nombre) || { count: 0, valor: 0 };
    d.count++;
    d.valor += c.valor_contrato;
    entMap.set(c.entidad_nombre, d);
  }
  const entidadesTop = [...entMap.entries()]
    .map(([nombre, d]) => ({ nombre, count: d.count, valor: d.valor }))
    .sort((a, b) => b.valor - a.valor)
    .slice(0, 10);

  return {
    totalContratos,
    valorTotal,
    promedioValor,
    activos,
    porEstado,
    porDepartamento,
    porMes,
    entidadesTop,
  };
}

